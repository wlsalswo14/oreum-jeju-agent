BC_TO_POS_MID = {
    "I56111": ["Q15", "Q02", "Q03", "Q06"], "I56112": ["Q12"], "I56113": ["Q10"], "I56114": ["Q07"],
    "I56119": ["Q04"], "I56192": ["Q14"], "I56211": ["Q08"], "I56219": ["Q01"], "I56220": ["Q13"], "G47215": ["Q11"],
}


@dataclass
class IndustryMatch:
    code: str
    name: str
    score: float
    matched: str = ""
    note: str = ""
    label: str = ""                  # 이용자 표현(예: '카페'); 정식 업종명으로 찾았으면 업종명
    store_keywords: list[str] = field(default_factory=list)
    pos_mid_codes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)

    def industry_sel_kwargs(self) -> dict:
        """analysis.common.IndustrySel 생성 인자."""
        return dict(code=self.code, name=self.name, label=self.label or self.name,
                    store_keywords=list(self.store_keywords))


@lru_cache(maxsize=1)
def biz42() -> list[dict]:
    return [dict(b) for b in load_catalog().reference.get("biz42", [])]


def biz_name(code: str) -> str:
    return next((b["name"] for b in biz42() if b["code"] == code), "")


def store_rule(code: str) -> dict:
    return dict(STORE_RULES.get(code, {"ksic": []}))


def store_keywords(code: str, include_related: bool = False) -> list[str]:
    r = STORE_RULES.get(code, {})
    return list(r.get("ksic", [])) + (list(r.get("related", [])) if include_related else [])


def pos_codes_for(code: str) -> list[dict]:
    mids = BC_TO_POS_MID.get(code, [])
    return [p for p in load_catalog().reference.get("pos_biz_codes", []) if p["mid_cd"] in mids]


def pos_lookup(text: str) -> list[dict]:
    """POS 외식업 업종코드표(참고표1)에서 이름·코드로 찾기. 예: '횟집' → Q10020."""
    t = re.sub(r"\s+", "", str(text or ""))
    out = []
    for p in load_catalog().reference.get("pos_biz_codes", []):
        names = [p["small_nm"], p["mid_nm"]] + re.split(r"[/&]", p["small_nm"]) + re.split(r"[/&]", p["mid_nm"])
        names = [n.replace(" ", "") for n in names if len(n.replace(" ", "")) >= 2]
        if t and (t in (p["small_cd"], p["mid_cd"]) or any(n in t or t in n for n in names)):
            out.append(dict(p))
    return out


def _mk(code: str, score: float, matched: str, note: str) -> IndustryMatch:
    rule = STORE_RULES.get(code, {})
    n = note or rule.get("note", "")
    return IndustryMatch(code=code, name=biz_name(code), score=score, matched=matched, note=n,
                         label=matched if matched and matched != code else biz_name(code),
                         store_keywords=store_keywords(code), pos_mid_codes=BC_TO_POS_MID.get(code, []))


def resolve_industry(text: str, limit: int = 5) -> list[IndustryMatch]:
    """자연어(예: '카페 창업', '흑돼지 고깃집', '렌터카')에서 BC 42업종 후보를 점수순으로 반환."""
    if not text:
        return []
    ts = re.sub(r"\s+", "", str(text))
    tsu = ts.upper()
    found: dict[str, IndustryMatch] = {}
    spans: list[tuple[int, int]] = []

    def add(m: IndustryMatch):
        if m.code not in found or found[m.code].score < m.score:
            found[m.code] = m

    for b in biz42():  # 코드·정식 업종명
        if b["code"] in tsu:
            add(_mk(b["code"], 1.0, b["code"], ""))
        nm = b["name"].replace(" ", "")
        i = ts.find(nm)
        if i >= 0:
            add(_mk(b["code"], 1.0, b["name"], ""))
            spans.append((i, i + len(nm)))
    for alias, code, sc, note in sorted(_ALIAS_ROWS, key=lambda r: len(r[0]), reverse=True):
        a = alias.upper() if alias.isascii() else alias
        start = 0
        while True:
            i = (tsu if alias.isascii() else ts).find(a, start)
            if i < 0:
                break
            start = i + 1
            if any(x <= i and i + len(a) <= y for x, y in spans):
                continue
            add(_mk(code, sc, alias, note))
            spans.append((i, i + len(a)))
    return sorted(found.values(), key=lambda m: -m.score)[:limit]


def classify_stores(df, include_related: bool = False):
    """허브 상가정보 DataFrame(793) 각 점포의 BC 42업종 코드(Series, 매칭 없으면 None)."""
    import pandas as pd

    kcol = "표준산업분류명" if "표준산업분류명" in df.columns else "std"
    m = {}
    for code, rule in STORE_RULES.items():
        for k in rule.get("ksic", []):
            m.setdefault(k, code)
        if include_related:
            for k in rule.get("related", []):
                m.setdefault(k, code)
    return pd.Series(df[kcol].astype(str).str.strip().map(m).values, index=df.index, dtype="object")


def count_competitors(code: str, stores=None, by: str = "법정동명", include_related: bool = False):
    """허브 793 상가정보로 법정동(기본)별 해당 업종 점포 수. 반환 DataFrame[by, store_cnt]."""
    if stores is None:
        from ..hub.public_data import stores as _stores
        stores = _stores()
    bc = classify_stores(stores, include_related=include_related)
    sub = stores[bc == code]
    g = sub.groupby(by, observed=True).size().rename("store_cnt").reset_index()
    g.attrs["source"] = "hub:793"
    return g.sort_values("store_cnt", ascending=False).reset_index(drop=True)


